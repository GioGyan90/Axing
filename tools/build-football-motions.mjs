import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {FOOTBALL_PLANS, MOTION_TIMING} from './football-plans.mjs';
import {createFootballRig} from '../scripts/game/football-rig.js';
const upstream = path.resolve(process.argv[2] || '../3D_AItool');
const lab = path.join(upstream, 'experiments/prompt2rig/public');
const [{createCharacter}, {Rig}, {planToTake, retargetTake}] = await Promise.all([
    import(pathToFileURL(path.join(lab, 'lab/character.js'))),
    import(pathToFileURL(path.join(lab, 'retarget.js'))),
    import(pathToFileURL(path.join(lab, 'lab/motion-plan.js'))),
]);
const driver = new Rig(createCharacter());
const clips = {};
for (const [id, plan] of Object.entries(FOOTBALL_PLANS)) {
    const take = planToTake(driver, plan);
    const {root} = createFootballRig();
    const target = new Rig(root);
    const clip = retargetTake(driver, target, take);
    const json = clip.toJSON();
    json.name = id;
    json.uuid = `axing-football-${id}-v1`;
    for (const track of json.tracks) {
        track.times = track.times.map(x => +x.toFixed(6));
        track.values = track.values.map(x => +x.toFixed(6));
    }
    clips[id] = json;
}
const out = fileURLToPath(new URL('../scripts/game/motions/football-clips.js', import.meta.url));
await fs.mkdir(path.dirname(out), {recursive: true});
await fs.writeFile(out, '// Generated by tools/build-football-motions.mjs using 3D_AItool Prompt2Rig.\n' +
    '// Source: GioGyan90/3D_AItool @ 0434ddfaee268531cf6141b8cbf19c6d64c2decf (Apache-2.0).\n' +
    `export const MOTION_TIMING = ${JSON.stringify(MOTION_TIMING)};\n` +
    `export const FOOTBALL_CLIPS = ${JSON.stringify(clips)};\n`);
await fs.writeFile(new URL('../scripts/game/motions/football.motion-plans.json', import.meta.url), JSON.stringify(FOOTBALL_PLANS, null, 2) + '\n');
console.log(JSON.stringify({clips: Object.keys(clips), bytes: (await fs.stat(out)).size, compiler: 'planToTake → retargetTake → trackToClip'}));
